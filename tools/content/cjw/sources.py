UA = {'User-Agent': 'CardJigsawWorld/1.0 (content tooling; contact matej@appwrite.io)'}
_last = {}

def _get_json(url, host_delay=0.6, timeout=40):
    host = urllib.parse.urlparse(url).netloc
    wait = host_delay - (time.time() - _last.get(host, 0))
    if wait > 0: time.sleep(wait)
    req = urllib.request.Request(url, headers=UA)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.load(r)
    finally:
        _last[host] = time.time()

def _strip(s):
    s = re.sub(r'<[^>]+>', '', s or '')
    return html.unescape(s).replace('\n', ' ').strip()

def _cand(**kw):
    c = dict(url='', thumb='', author='Unknown', source='', licence='', page='', title='', text='', w=0, h=0, provider='')
    c.update(kw)
    c['thumb'] = c['thumb'] or c['url']
    c['author'] = (c['author'] or 'Unknown')[:90]
    c['title'] = c['title'][:90]
    return c

# ---------------- Wikimedia Commons ----------------
# Commons only renders a fixed list of thumbnail widths for anonymous clients (960 and 1280 work).
def _canon(u):
    u = u.split('?')[0].replace('https://thumb.wikimedia.org/', 'https://upload.wikimedia.org/')
    return u

def _small(u):
    return re.sub(r'/1280px-', '/960px-', u) if '/1280px-' in u else u

def _author(a):
    a = (a or '').strip()
    a = re.sub(r'^(User|Benutzer|Utilisateur):', '', a).strip()
    return a or 'Unknown'

def _ai_tag(cand, categories):
    """AI-generated files: name the generator in the author and mark the source so the app never implies human authorship."""
    m = re.search(r'Images generated by ([^|]+)', categories or '')
    if m or 'AI-generated' in (categories or '') or 'Text-to-image' in (categories or ''):
        gen = m.group(1).strip() if m else 'AI'
        gen = gen.replace(' (text-to-image model)', '').replace('Image Creator by Microsoft Bing', 'Bing Image Creator')
        cand['author'] = f"{cand['author']} / {gen}"[:90]
        cand['source'] = f"Wikimedia Commons, {cand['licence']} (AI-generated)"[:128]
        cand['ai'] = True
    return cand

def commons_search(query, limit=40, offset=0, quality=True, min_h=1000, extra='', quality_cat=None):
    """Search Commons files. quality=True restricts to Quality/Featured images (curated, usually well composed);
    quality_cat='Quality images of food' uses that curated tree (deepcategory) instead."""
    q = query
    if quality and quality_cat:
        q = f'({query}) deepcategory:"{quality_cat}"'
    elif quality:
        q = f'({query}) (incategory:"Quality images" OR incategory:"Featured pictures on Wikimedia Commons" OR incategory:"Valued images")'
    q += f' filetype:bitmap fileh:>{min_h} {extra}'
    params = dict(action='query', generator='search', gsrsearch=q, gsrnamespace=6, gsrlimit=limit, gsroffset=offset,
                  prop='imageinfo', iiprop='url|size|extmetadata|mime', iiurlwidth=1200, iiextmetadatafilter='LicenseShortName|Artist|ImageDescription|Categories|Restrictions|ObjectName|Credit',
                  format='json', formatversion=2)
    url = 'https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(params)
    try:
        d = _get_json(url)
    except Exception as e:
        print('  commons error', str(e)[:100]); return []
    out = []
    for p in d.get('query', {}).get('pages', []):
        ii = (p.get('imageinfo') or [None])[0]
        if not ii: continue
        em = ii.get('extmetadata', {})
        g = lambda k: _strip(em.get(k, {}).get('value', ''))
        lic = g('LicenseShortName')
        if not filters.licence_ok(lic): continue
        if 'personality' in g('Restrictions').lower(): continue
        if ii.get('mime') not in ('image/jpeg', 'image/png', 'image/webp'): continue
        w, h = ii.get('width', 0), ii.get('height', 0)
        thumb = _canon(ii.get('thumburl') or ii['url'])
        tw, th = ii.get('thumbwidth', w), ii.get('thumbheight', h)
        title = p['title'].removeprefix('File:')
        title = re.sub(r'\.(jpe?g|png|webp)$', '', title, flags=re.I).replace('_', ' ')
        desc = g('ImageDescription')
        small = _small(thumb)
        out.append(_cand(url=thumb, thumb=small, author=_author(g('Artist') or g('Credit')),
                         source=f'Wikimedia Commons, {lic}', licence=lic, page=ii.get('descriptionurl', ''),
                         title=title, text=' '.join([title, desc, g('Categories'), g('ObjectName')]),
                         w=tw, h=th, orig_w=w, orig_h=h, provider='commons', commons_title=p['title']))
        _ai_tag(out[-1], g('Categories'))
    return out

def commons_subcats(cat, depth=1, _seen=None):
    """Recursively list subcategory titles (breadth-first, bounded)."""
    _seen = _seen if _seen is not None else set()
    title = cat if cat.startswith('Category:') else 'Category:' + cat
    out = []
    if depth <= 0 or title in _seen: return out
    _seen.add(title)
    params = dict(action='query', list='categorymembers', cmtitle=title, cmtype='subcat', cmlimit=200, format='json', formatversion=2)
    try:
        d = _get_json('https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(params))
    except Exception as e:
        print('  commons error', str(e)[:100]); return out
    for m in d.get('query', {}).get('categorymembers', []):
        t = m['title']
        if t in _seen: continue
        out.append(t)
        out += commons_subcats(t, depth - 1, _seen)
    return out

def commons_category_deep(cat, limit=300, depth=2, per_cat=120):
    """Files of a category and its subcategories (depth levels), de-duplicated."""
    cats = [cat if cat.startswith('Category:') else 'Category:' + cat] + commons_subcats(cat, depth)
    seen, out = set(), []
    for c in cats:
        if len(out) >= limit: break
        for f in commons_category(c, limit=per_cat):
            if f['url'] in seen: continue
            seen.add(f['url']); out.append(f)
    return out

def commons_category(cat, limit=200, cont=None):
    """List files in a Commons category (one page) with metadata."""
    params = dict(action='query', generator='categorymembers', gcmtitle=cat if cat.startswith('Category:') else 'Category:' + cat,
                  gcmtype='file', gcmlimit=min(limit, 50), prop='imageinfo', iiprop='url|size|extmetadata|mime', iiurlwidth=1200,
                  iiextmetadatafilter='LicenseShortName|Artist|ImageDescription|Categories|Restrictions|ObjectName|Credit',
                  format='json', formatversion=2)
    out, seen_cont = [], cont
    while len(out) < limit:
        if seen_cont: params['gcmcontinue'] = seen_cont
        url = 'https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(params)
        try:
            d = _get_json(url)
        except Exception as e:
            print('  commons error', str(e)[:100]); break
        for p in d.get('query', {}).get('pages', []):
            ii = (p.get('imageinfo') or [None])[0]
            if not ii: continue
            em = ii.get('extmetadata', {})
            g = lambda k: _strip(em.get(k, {}).get('value', ''))
            lic = g('LicenseShortName')
            if not filters.licence_ok(lic): continue
            if ii.get('mime') not in ('image/jpeg', 'image/png', 'image/webp'): continue
            thumb = _canon(ii.get('thumburl') or ii['url'])
            title = re.sub(r'\.(jpe?g|png|webp)$', '', p['title'].removeprefix('File:'), flags=re.I).replace('_', ' ')
            small = _small(thumb)
            out.append(_cand(url=thumb, thumb=small, author=_author(g('Artist') or g('Credit')),
                             source=f'Wikimedia Commons, {lic}', licence=lic, page=ii.get('descriptionurl', ''),
                             title=title, text=' '.join([title, g('ImageDescription'), g('Categories'), g('ObjectName')]),
                             w=ii.get('thumbwidth', ii.get('width', 0)), h=ii.get('thumbheight', ii.get('height', 0)),
                             orig_w=ii.get('width', 0), orig_h=ii.get('height', 0), provider='commons', commons_title=p['title']))
            _ai_tag(out[-1], g('Categories'))
        seen_cont = d.get('continue', {}).get('gcmcontinue')
        if not seen_cont: break
    return out

# ---------------- Openverse (anonymous: 200 requests/day, 20/min) ----------------
BUDGET = CACHE / 'openverse-budget.json'
DAILY_LIMIT = 190

def openverse_budget_left():
    today = dt.date.today().isoformat()
    b = json.loads(BUDGET.read_text()) if BUDGET.exists() else {}
    return DAILY_LIMIT - b.get(today, 0)

def _openverse_spend():
    with locked('openverse'):
        today = dt.date.today().isoformat()
        b = json.loads(BUDGET.read_text()) if BUDGET.exists() else {}
        b = {today: b.get(today, 0) + 1}
        BUDGET.write_text(json.dumps(b))

def openverse_search(query, page=1, category='photograph', aspect='tall,square'):
    if openverse_budget_left() <= 0:
        print('  openverse budget exhausted for today'); return []
    params = dict(q=query, license='cc0,pdm,by,by-sa', category=category, aspect_ratio=aspect, size='medium,large',
                  mature='false', page_size=20, page=page)
    url = 'https://api.openverse.org/v1/images/?' + urllib.parse.urlencode(params)
    _openverse_spend()
    try:
        d = _get_json(url, host_delay=3.2)
    except urllib.error.HTTPError as e:
        print('  openverse http', e.code); return []
    except Exception as e:
        print('  openverse error', str(e)[:100]); return []
    out = []
    for r in d.get('results', []):
        lic = (r.get('license') or '').lower()
        if lic not in ('cc0', 'pdm', 'by', 'by-sa'): continue
        u = r.get('url') or ''
        if not u.startswith('https://'): continue
        tags = ' '.join(t.get('name', '') for t in (r.get('tags') or []))
        licname = {'cc0': 'CC0', 'pdm': 'Public Domain Mark', 'by': 'CC BY', 'by-sa': 'CC BY-SA'}[lic]
        out.append(_cand(url=u, author=r.get('creator') or 'Unknown', source=f"{r.get('source', 'openverse')} via Openverse, {licname}",
                         licence=licname, page=r.get('foreign_landing_url', ''), title=r.get('title') or '',
                         text=' '.join([r.get('title') or '', tags]), w=r.get('width') or 0, h=r.get('height') or 0,
                         provider='openverse:' + (r.get('source') or '')))
    return out

# ---------------- Cleveland Museum of Art (CC0) ----------------
CMA_TYPES = ('Painting', 'Print', 'Drawing', 'Textile', 'Photograph', 'Miscellaneous', 'Tapestry', 'Glass', 'Ceramic', 'Lacquer', 'Enamel', 'Wood', 'Jewelry')

def cma_search(query, limit=80, types=CMA_TYPES, skip=0):
    params = dict(q=query, cc0=1, has_image=1, limit=limit, skip=skip,
                  fields='id,title,creators,creation_date,images,type,description,culture,technique,url')
    url = 'https://openaccess-api.clevelandart.org/api/artworks/?' + urllib.parse.urlencode(params)
    try:
        d = _get_json(url)
    except Exception as e:
        print('  cma error', str(e)[:100]); return []
    out = []
    for a in d.get('data', []):
        img = (a.get('images') or {}).get('web')
        if not img or (types and a.get('type') not in types): continue
        try:
            w, h = int(float(img['width'])), int(float(img['height']))
        except Exception:
            continue
        cr = (a.get('creators') or [{}])[0].get('description', '') or 'Unknown artist'
        out.append(_cand(url=img['url'], author=cr.split(' (')[0], source='Cleveland Museum of Art, CC0', licence='CC0',
                         page=a.get('url', ''), title=(a.get('title') or '').split(' (')[0],
                         text=' '.join([a.get('title') or '', a.get('description') or '', a.get('type') or '', ' '.join(a.get('culture') or [])]),
                         w=w, h=h, provider='cma'))
    return out

# ---------------- NASA image library (public domain) ----------------
def nasa_search(query, page=1, page_size=50):
    params = dict(q=query, media_type='image', page=page, page_size=page_size)
    url = 'https://images-api.nasa.gov/search?' + urllib.parse.urlencode(params)
    try:
        d = _get_json(url)
    except Exception as e:
        print('  nasa error', str(e)[:100]); return []
    out = []
    for it in d.get('collection', {}).get('items', []):
        data = (it.get('data') or [{}])[0]; nid = data.get('nasa_id')
        if not nid: continue
        u = f'https://images-assets.nasa.gov/image/{nid}/{nid}~medium.jpg'
        out.append(_cand(url=u, author=(data.get('photographer') or data.get('secondary_creator') or 'NASA'), source='NASA Image and Video Library, public domain',
                         licence='Public domain (NASA)', page=f'https://images.nasa.gov/details/{nid}', title=data.get('title') or '',
                         text=' '.join([data.get('title') or '', data.get('description') or '', ' '.join(data.get('keywords') or [])]),
                         provider='nasa'))
    return out

